// Liturgy texts live in assets/liturgy/<id>.<lang>.ltxt (JSON: { header, blocks, source }), not in
// the JS bundle. This script
//   1. converts any legacy src/liturgy/data/<id>.<lang>.ts file into an asset (only needed while
//      such files exist; the assets are now the source of truth), and
//   2. regenerates src/liturgy/data/index.ts, the static require() map Metro needs.
// Run: node scripts/build-liturgy-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'src', 'liturgy', 'data');
const assetDir = path.join(root, 'assets', 'liturgy');
const FILE = /^(.+)\.(cu|en|ru|tr)$/;

fs.mkdirSync(assetDir, { recursive: true });

for (const name of fs.readdirSync(dataDir)) {
  const m = FILE.exec(name.replace(/\.ts$/, ''));
  if (!name.endsWith('.ts') || !m) continue;
  const src = fs.readFileSync(path.join(dataDir, name), 'utf8');
  const header = src
    .split('\n')
    .filter((line) => line.startsWith('//'))
    .map((line) => line.slice(3))
    .join('\n');
  const js = src
    .replace(/^import type .*$/m, '')
    .replace(/export const blocks[^=]*=/, 'const blocks =')
    .replace(/export const source[^=]*=/, 'const source =');
  const { blocks, source } = new Function(`${js}\nreturn { blocks, source };`)();
  fs.writeFileSync(
    path.join(assetDir, `${m[1]}.${m[2]}.ltxt`),
    JSON.stringify({ header, blocks, source }),
    'utf8',
  );
}

const byId = new Map();
for (const name of fs.readdirSync(assetDir).sort()) {
  const m = /^(.+)\.(cu|en|ru|tr)\.ltxt$/.exec(name);
  if (!m) continue;
  if (!byId.has(m[1])) byId.set(m[1], []);
  byId.get(m[1]).push(m[2]);
}

const order = ['cu', 'en', 'ru', 'tr'];
let out = `// GENERATED by scripts/build-liturgy-assets.mjs - do not edit. Metro needs static require()
// strings, so every text file of assets/liturgy is listed here.
import type { LiturgyLoaders } from '../types';
import { assetLoader } from '../assetLoader';

export const LOADERS: LiturgyLoaders = {
`;
for (const [id, langs] of byId) {
  out += `  '${id}': {\n`;
  for (const lang of order.filter((l) => langs.includes(l))) {
    out += `    ${lang}: assetLoader(require('../../../assets/liturgy/${id}.${lang}.ltxt'), '${id}.${lang}'),\n`;
  }
  out += '  },\n';
}
out += '};\n';
fs.writeFileSync(path.join(dataDir, 'index.ts'), out, 'utf8');
console.log(`${byId.size} services, ${[...byId.values()].flat().length} text files`);
