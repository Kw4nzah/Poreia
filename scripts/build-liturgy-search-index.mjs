// Builds the full-text search index of the services (assets/liturgy-index/<lang>.ltxt) from the text
// assets (assets/liturgy/<id>.<lang>.ltxt), plus the static require() map Metro needs
// (src/liturgy/data/searchIndex.ts). Needs Node 22.18+ (it imports the .ts folding function).
// Run after build-liturgy-assets.mjs: node scripts/build-liturgy-search-index.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildIndex } from './liturgySearchIndex.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const textDir = path.join(root, 'assets', 'liturgy');
const indexDir = path.join(root, 'assets', 'liturgy-index');
const LANGS = ['cu', 'en', 'ru', 'tr'];

fs.mkdirSync(indexDir, { recursive: true });
const written = [];
let total = 0;
for (const lang of LANGS) {
  const docs = [];
  for (const name of fs.readdirSync(textDir).sort()) {
    const m = /^(.+)\.(cu|en|ru|tr)\.ltxt$/.exec(name);
    if (!m || m[2] !== lang) continue;
    const { blocks } = JSON.parse(fs.readFileSync(path.join(textDir, name), 'utf8'));
    docs.push({ id: m[1], texts: blocks.filter((b) => b.who !== 'omitted').map((b) => b.text) });
  }
  if (docs.length === 0) continue;
  const json = JSON.stringify(buildIndex(docs));
  fs.writeFileSync(path.join(indexDir, `${lang}.ltxt`), json, 'utf8');
  written.push(lang);
  total += Buffer.byteLength(json);
  console.log(`${lang}: ${docs.length} services, ${(Buffer.byteLength(json) / 1024).toFixed(0)} KiB`);
}
console.log(`total ${(total / 1024 / 1024).toFixed(2)} MiB`);

let out = `// GENERATED by scripts/build-liturgy-search-index.mjs - do not edit. Metro needs static require()
// strings, so every index file of assets/liturgy-index is listed here.
import type { LiturgyLanguage } from '../types';

export const SEARCH_INDEX_ASSETS: Partial<Record<LiturgyLanguage, number>> = {
`;
for (const lang of written) out += `  ${lang}: require('../../../assets/liturgy-index/${lang}.ltxt'),\n`;
out += '};\n';
fs.writeFileSync(path.join(root, 'src', 'liturgy', 'data', 'searchIndex.ts'), out, 'utf8');
